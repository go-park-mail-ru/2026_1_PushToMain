CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;


CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    email         TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,

    name      TEXT NOT NULL,
    surname   TEXT NOT NULL,
    is_male   BOOLEAN,
    birthdate DATE,

    image_path TEXT,

    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT email_length_check         CHECK (char_length(email) < 256),
    CONSTRAINT password_hash_check        CHECK (char_length(password_hash) <= 256),
    CONSTRAINT name_length_check          CHECK (char_length(name) < 256),
    CONSTRAINT surname_length_check       CHECK (char_length(surname) < 256),
    CONSTRAINT image_path_length_check    CHECK (char_length(image_path) < 2048)
);

CREATE TABLE emails (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    sender_id    BIGINT REFERENCES users(id) ON DELETE SET NULL,
    sender_email TEXT   NOT NULL,

    header TEXT,
    body   TEXT,

    is_draft BOOLEAN NOT NULL DEFAULT false,

    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT header_length_check       CHECK (char_length(header) < 255),
    CONSTRAINT sender_email_length_check CHECK (char_length(sender_email) < 256),
    CONSTRAINT draft_has_internal_sender CHECK (NOT is_draft OR sender_id IS NOT NULL)
);

CREATE TABLE email_recipients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    email_id          BIGINT NOT NULL REFERENCES emails(id) ON DELETE CASCADE,
    recipient_user_id BIGINT          REFERENCES users(id)  ON DELETE SET NULL,
    recipient_email   TEXT   NOT NULL,

    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT recipient_email_length_check CHECK (char_length(recipient_email) < 256),
    UNIQUE (email_id, recipient_email)
);

CREATE TABLE user_emails (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id  BIGINT NOT NULL REFERENCES users(id)  ON DELETE CASCADE,
    email_id BIGINT NOT NULL REFERENCES emails(id) ON DELETE CASCADE,

    is_read    BOOLEAN NOT NULL DEFAULT false,
    is_starred BOOLEAN NOT NULL DEFAULT false,
    is_spam    BOOLEAN NOT NULL DEFAULT false,
    is_deleted BOOLEAN NOT NULL DEFAULT false,
    is_inbox BOOLEAN NOT NULL DEFAULT true,

    is_sender BOOLEAN NOT NULL DEFAULT false,

    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP

);

CREATE TABLE attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    email_id BIGINT NOT NULL REFERENCES emails(id) ON DELETE CASCADE,

    filename     TEXT     NOT NULL,
    content_type TEXT     NOT NULL,
    size_bytes   BIGINT   NOT NULL,

    storage_path TEXT     NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT size_positive   CHECK (size_bytes > 0),
    CONSTRAINT filename_length CHECK (char_length(filename) < 512)
);

CREATE TABLE folders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name    TEXT   NOT NULL,

    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,

    UNIQUE (user_id, name)
);

CREATE TABLE folder_emails (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    folder_id     BIGINT NOT NULL REFERENCES folders(id)     ON DELETE CASCADE,
    user_email_id BIGINT NOT NULL REFERENCES user_emails(id) ON DELETE CASCADE,

    created_at timestamptz NOT NULL DEFAULT NOW(),
    UNIQUE (folder_id, user_email_id)
);

CREATE TABLE spam_senders (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, sender_id)
);


CREATE TABLE support_admins (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE support_tickets (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    support_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    subject TEXT NOT NULL,
    category TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'open',
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at  timestamptz,

    CONSTRAINT subject_length_check CHECK (char_length(subject) BETWEEN 1 AND 255),
    CONSTRAINT category_check CHECK (category IN ('bug','proposal','complaint','other')),
    CONSTRAINT status_check CHECK (status IN ('open','in_progress','closed')),
    CONSTRAINT closed_at_consistency CHECK (
        (status = 'closed' AND closed_at IS NOT NULL) OR
        (status <> 'closed' AND closed_at IS NULL)
    )
);

CREATE INDEX idx_support_tickets_user ON support_tickets(user_id, created_at DESC);
CREATE INDEX idx_support_tickets_status ON support_tickets(status);
CREATE INDEX idx_support_tickets_support_id ON support_tickets(support_id) WHERE support_id IS NOT NULL;

CREATE TABLE support_messages (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES support_tickets(id) ON DELETE CASCADE,
    author_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    body TEXT NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT body_length_check CHECK (char_length(body) BETWEEN 1 AND 10000)
);

CREATE INDEX idx_support_messages_ticket ON support_messages(ticket_id, id);

CREATE TRIGGER trigger_update_updated_at
    BEFORE UPDATE ON support_tickets
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

CREATE INDEX idx_emails_sender_drafts
    ON emails(sender_id, updated_at DESC)
    WHERE is_draft = true;

CREATE INDEX idx_emails_sender_sent
    ON emails(sender_id, created_at DESC)
    WHERE is_draft = false;

CREATE INDEX idx_email_recipients_email_id
    ON email_recipients(email_id);

CREATE INDEX idx_email_recipients_user_id
    ON email_recipients(recipient_user_id)
    WHERE recipient_user_id IS NOT NULL;

CREATE INDEX idx_user_emails_inbox
    ON user_emails(user_id, created_at DESC)
    WHERE is_deleted = false AND is_spam = false;

CREATE INDEX idx_user_emails_starred
    ON user_emails(user_id, updated_at DESC)
    WHERE is_starred = true AND is_deleted = false;

CREATE INDEX idx_user_emails_spam
    ON user_emails(user_id, created_at DESC)
    WHERE is_spam = true;

CREATE INDEX idx_user_emails_trash
    ON user_emails(user_id, updated_at DESC)
    WHERE is_deleted = true;

CREATE INDEX idx_attachments_email_id ON attachments(email_id);

CREATE INDEX idx_spam_senders_user_id ON spam_senders(user_id);
